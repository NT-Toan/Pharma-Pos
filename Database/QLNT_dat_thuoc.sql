IF OBJECT_ID(N'dbo.DONDATTHUOC', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.DONDATTHUOC (
        MADON INT IDENTITY(1,1) PRIMARY KEY,
        HOTEN NVARCHAR(100) NOT NULL,
        SDT VARCHAR(15) NOT NULL,
        DIACHI NVARCHAR(200) NOT NULL,
        GHICHU NVARCHAR(500) NULL,
        NGAYDAT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
        TRANGTHAI VARCHAR(20) NOT NULL DEFAULT 'Moi',
        TONGTAMTINH DECIMAL(18,2) NOT NULL,
        CONSTRAINT CK_DONDATTHUOC_TONG CHECK (TONGTAMTINH >= 0),
        CONSTRAINT CK_DONDATTHUOC_TRANGTHAI CHECK (TRANGTHAI IN ('Moi', 'DaXacNhan', 'DaHuy'))
    );
END;

-- Thông tin voucher lưu dạng bản chụp để đơn cũ không đổi khi sửa chương trình KM.
