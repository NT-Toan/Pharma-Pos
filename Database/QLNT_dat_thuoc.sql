    ALTER TABLE dbo.HOADON ADD CONSTRAINT CK_HOADON_TRANGTHAITT
        CHECK (TRANGTHAITT IN ('DaThanhToan', 'ChoThuTien'));

IF OBJECT_ID(N'dbo.CTDONDATTHUOC', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CTDONDATTHUOC (
        MADON INT NOT NULL,
        MATHUOC VARCHAR(10) NOT NULL,
        SOLUONG INT NOT NULL,
        DONGIADUKIEN DECIMAL(18,2) NOT NULL,
        CONSTRAINT PK_CTDONDATTHUOC PRIMARY KEY (MADON, MATHUOC),
        CONSTRAINT FK_CTDONDATTHUOC_DON FOREIGN KEY (MADON)
            REFERENCES dbo.DONDATTHUOC(MADON),
        CONSTRAINT FK_CTDONDATTHUOC_THUOC FOREIGN KEY (MATHUOC)
            REFERENCES dbo.THUOC(MATHUOC),
        CONSTRAINT CK_CTDONDATTHUOC_SOLUONG CHECK (SOLUONG > 0),
        CONSTRAINT CK_CTDONDATTHUOC_DONGIA CHECK (DONGIADUKIEN >= 0)
    );
END;
IF COL_LENGTH(N'dbo.CTDONDATTHUOC', N'THANHTIEN') IS NULL
    ALTER TABLE dbo.CTDONDATTHUOC ADD THANHTIEN DECIMAL(18,2) NULL;
GO
UPDATE dbo.CTDONDATTHUOC SET THANHTIEN = DONGIADUKIEN * SOLUONG WHERE THANHTIEN IS NULL;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'dbo.CTDONDATTHUOC')
    AND name = N'THANHTIEN' AND is_nullable = 1)
    ALTER TABLE dbo.CTDONDATTHUOC ALTER COLUMN THANHTIEN DECIMAL(18,2) NOT NULL;
