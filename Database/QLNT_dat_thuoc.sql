        CONSTRAINT DF_DONDATTHUOC_TIENGIAM DEFAULT 0;
IF COL_LENGTH(N'dbo.DONDATTHUOC', N'GIAMSANPHAM') IS NULL
    ALTER TABLE dbo.DONDATTHUOC ADD GIAMSANPHAM DECIMAL(18,2) NOT NULL
        CONSTRAINT DF_DONDATTHUOC_GIAMSANPHAM DEFAULT 0;
IF COL_LENGTH(N'dbo.DONDATTHUOC', N'MACTKM_HD') IS NULL
    ALTER TABLE dbo.DONDATTHUOC ADD MACTKM_HD VARCHAR(10) NULL;
IF COL_LENGTH(N'dbo.DONDATTHUOC', N'MUCTIENHD') IS NULL
    ALTER TABLE dbo.DONDATTHUOC ADD MUCTIENHD DECIMAL(18,2) NULL;

-- Đơn cũ chưa trừ tồn; chỉ đơn mới có giá trị 1 mới được hoàn tồn khi hủy.
