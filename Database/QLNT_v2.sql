-- ============================================================
-- QLNT - Quan ly nha thuoc (phien ban 2)
-- Thay doi so voi ban dau:
--   + Them bang THAMSO (MATHAMSO, GIATRI)
--   + KHACHHANG: them DIACHI
--   + HOADON: them MAVOUCHER, (MACTKM_HD, MUCTIENHD), TIENGIAM
--   + KM_VOUCHER: them MAKH (lien ket KHACHHANG), bo UNIQUE (MAVOUCHER, MACTKM)
--   + KM_HOADON: bo cot MAVOUCHER va FK toi KM_VOUCHER, them FK toi CTKHUYENMAI
--   + Doi thu tu tao bang: nhom khuyen mai phai co truoc HOADON
-- Ma tu sinh (HD0001, PN0001, KH0001...) do lop BUS tao, xem MaTuDong.cs
-- File de ASCII de tranh loi font khi mo bang cac cong cu khac nhau.
-- ============================================================

-- 1. LOAITHUOC (ma tu sinh: LT0001)
CREATE TABLE LOAITHUOC (
    MALOAI VARCHAR(10) PRIMARY KEY,
    TENLOAI NVARCHAR(100) NOT NULL
);

-- 2. THUOC (ma tu sinh: TH0001)
CREATE TABLE THUOC (
    MATHUOC VARCHAR(10) PRIMARY KEY,
    TENTHUOC NVARCHAR(100) NOT NULL,
    HSD DATE,
    DONGIA DECIMAL(18,2) NOT NULL,
    SOLUONG INT NOT NULL DEFAULT 0,
    MALOAI VARCHAR(10) NOT NULL,
    FOREIGN KEY (MALOAI) REFERENCES LOAITHUOC(MALOAI),
    CHECK (DONGIA > 0),
    CHECK (SOLUONG >= 0)
);

-- 3. NHANVIEN (ma tu sinh: NV0001)
CREATE TABLE NHANVIEN (
    MANV VARCHAR(10) PRIMARY KEY,
    HOTENNV NVARCHAR(100) NOT NULL,
    CHUCVU NVARCHAR(50),
    LUONG DECIMAL(18,2),
    CHECK (LUONG >= 0)
);

-- 4. KHACHHANG (ma tu sinh: KH0001)
CREATE TABLE KHACHHANG (
    MAKH VARCHAR(10) PRIMARY KEY,
    HOTEN NVARCHAR(100) NOT NULL,
    SDT VARCHAR(15),
    DIACHI NVARCHAR(200)
);

-- 5. NHACUNGCAP (ma tu sinh: NCC0001)
CREATE TABLE NHACUNGCAP (
    MANCC VARCHAR(10) PRIMARY KEY,
    TENNCC NVARCHAR(100) NOT NULL,
    DIACHI NVARCHAR(200),
    SDT VARCHAR(15)
);

-- 6. CTKHUYENMAI (ma tu sinh: KM0001)
CREATE TABLE CTKHUYENMAI (
    MACTKM VARCHAR(10) PRIMARY KEY,
    TENCTKM NVARCHAR(100) NOT NULL,
    NGAYBATDAU DATE,
    NGAYKETTHUC DATE,
    CHECK (NGAYKETTHUC >= NGAYBATDAU)
);

-- 7. KM_SANPHAM: giam gia theo san pham
CREATE TABLE KM_SANPHAM (
    MACTKM VARCHAR(10),
    MATHUOC VARCHAR(10),
    PHANTRAMGIAM DECIMAL(5,2) NOT NULL,
    PRIMARY KEY (MACTKM, MATHUOC),
    FOREIGN KEY (MACTKM) REFERENCES CTKHUYENMAI(MACTKM),
    FOREIGN KEY (MATHUOC) REFERENCES THUOC(MATHUOC),
    CHECK (PHANTRAMGIAM BETWEEN 0 AND 100)
);

-- 8. KM_VOUCHER: voucher thuoc 1 chuong trinh KM, gan voi khach hang
--    MAVOUCHER do nguoi dung dat (vd TET2026), BUS kiem tra trung
--    MAKH = NULL: voucher chung, ai cung dung duoc
CREATE TABLE KM_VOUCHER (
    MAVOUCHER VARCHAR(20) PRIMARY KEY,
    MACTKM VARCHAR(10) NOT NULL,
    MAKH VARCHAR(10),
    PHANTRAMGIAM DECIMAL(5,2) NOT NULL,
    FOREIGN KEY (MACTKM) REFERENCES CTKHUYENMAI(MACTKM),
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH),
    CHECK (PHANTRAMGIAM BETWEEN 0 AND 100)
);

-- 9. KM_HOADON: hoa don dat muc tien MUCTIENHD tro len thi giam PHANTRAMGIAM %
--    Doc lap voi voucher
CREATE TABLE KM_HOADON (
    MACTKM VARCHAR(10) NOT NULL,
    MUCTIENHD DECIMAL(18,2) NOT NULL,
    PHANTRAMGIAM DECIMAL(5,2) NOT NULL,
    PRIMARY KEY (MACTKM, MUCTIENHD),
    FOREIGN KEY (MACTKM) REFERENCES CTKHUYENMAI(MACTKM),
    CHECK (MUCTIENHD >= 0),
    CHECK (PHANTRAMGIAM BETWEEN 0 AND 100)
);

-- 10. HOADON (ma tu sinh: HD0001)
--    MAVOUCHER            : voucher da dung (moi hoa don toi da 1 voucher), NULL neu khong dung
--    MACTKM_HD, MUCTIENHD : moc KM_HOADON da ap dung, NULL neu khong co
--    TIENGIAM             : tong tien giam o cap hoa don (KM_HOADON + voucher), luu lai de
--                           sau nay doi % khuyen mai khong lam sai hoa don cu
--    TONGTIEN             : = SUM(CTHD.THANHTIEN) - TIENGIAM
CREATE TABLE HOADON (
    MAHD VARCHAR(10) PRIMARY KEY,
    MANV VARCHAR(10) NOT NULL,
    NGAYLAP DATE NOT NULL,
    TONGTIEN DECIMAL(18,2) NOT NULL DEFAULT 0,
    MAKH VARCHAR(10),
    MAVOUCHER VARCHAR(20),
    MACTKM_HD VARCHAR(10),
    MUCTIENHD DECIMAL(18,2),
    TIENGIAM DECIMAL(18,2) NOT NULL DEFAULT 0,
    TIENKHACHDUA DECIMAL(18,2),
    PHUONGTHUCTT VARCHAR(12) NOT NULL DEFAULT 'TaiCuaHang',
    TRANGTHAITT VARCHAR(15) NOT NULL DEFAULT 'DaThanhToan',
    FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH),
    FOREIGN KEY (MAVOUCHER) REFERENCES KM_VOUCHER(MAVOUCHER),
    FOREIGN KEY (MACTKM_HD, MUCTIENHD) REFERENCES KM_HOADON(MACTKM, MUCTIENHD),
    CHECK (TONGTIEN >= 0),
    CHECK (TIENGIAM >= 0),
    CHECK (TIENKHACHDUA IS NULL OR TIENKHACHDUA >= 0),
    CHECK (PHUONGTHUCTT IN ('Online', 'TaiCuaHang', 'COD')),
    CHECK (TRANGTHAITT IN ('DaThanhToan', 'ChoThuTien')),
    CHECK ((MACTKM_HD IS NULL AND MUCTIENHD IS NULL)
        OR (MACTKM_HD IS NOT NULL AND MUCTIENHD IS NOT NULL))
);

-- 11. CTHD
CREATE TABLE CTHD (
    MAHD VARCHAR(10),
    MATHUOC VARCHAR(10),
    SOLUONG INT NOT NULL,
    DONGIA DECIMAL(18,2) NOT NULL,
    THANHTIEN DECIMAL(18,2) NOT NULL,
    PRIMARY KEY (MAHD, MATHUOC),
    FOREIGN KEY (MAHD) REFERENCES HOADON(MAHD),
    FOREIGN KEY (MATHUOC) REFERENCES THUOC(MATHUOC),
    CHECK (SOLUONG > 0),
    CHECK (DONGIA >= 0),
    CHECK (THANHTIEN >= 0)
);

-- 12. PHIEUNHAP (ma tu sinh: PN0001)
CREATE TABLE PHIEUNHAP (
    MAPN VARCHAR(10) PRIMARY KEY,
    MANCC VARCHAR(10) NOT NULL,
    MANV VARCHAR(10) NOT NULL,
    NGAYNHAP DATE NOT NULL,
    TONGTIEN DECIMAL(18,2) NOT NULL DEFAULT 0,
    FOREIGN KEY (MANCC) REFERENCES NHACUNGCAP(MANCC),
    FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CHECK (TONGTIEN >= 0)
);

-- 13. CTPN
CREATE TABLE CTPN (
    MATHUOC VARCHAR(10),
    MAPN VARCHAR(10),
    SOLUONG INT NOT NULL,
    DONGIA DECIMAL(18,2) NOT NULL,
    PRIMARY KEY (MATHUOC, MAPN),
    FOREIGN KEY (MATHUOC) REFERENCES THUOC(MATHUOC),
    FOREIGN KEY (MAPN) REFERENCES PHIEUNHAP(MAPN),
    CHECK (SOLUONG > 0),
    CHECK (DONGIA >= 0)
);

-- 14. THAMSO: bang tham so (code, value), luu cac hang so he thong co the thay doi
--    GIATRI luu dang chuoi, BUS tu ep kieu khi dung (so ngay, so luong...)
CREATE TABLE THAMSO (
    MATHAMSO VARCHAR(50) PRIMARY KEY,
    GIATRI NVARCHAR(200) NOT NULL
);

